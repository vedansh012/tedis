/**
 * The seeded community: twenty people.
 *
 * Hand-written rather than generated. At this size a template ("{role} at
 * {company}, passionate about {topic}") is obvious by the third profile, and the
 * brief for this data was explicitly that no two bios read alike. Twenty is also
 * few enough that each person can carry a real point of view, which is what
 * makes the feed read as a community instead of a table.
 *
 * Every account here is fictional. Names are ordinary and combined at random;
 * companies are invented, universities are real institutions used only as a
 * place-of-study string. Nothing is attributed to a real person, and every row
 * is written with `isSeeded: true` so it can be told apart from a real signup
 * (and removed) without guessing.
 */

import { avatar, BANNERS } from "./media";

export interface Person {
  /** Stable key used to wire posts, comments and follows to this person. */
  key: string;
  displayName: string;
  username: string;
  /** Profile.headline — current focus, not a job title (see schema). */
  headline: string;
  bio: string;
  location: string;
  /** Free text: an employer, "self-employed", or a year and university. */
  company: string;
  experienceLevel: "Student" | "Junior" | "Mid" | "Senior" | "Staff" | "Principal" | "Founder";
  websiteUrl: string | null;
  pronouns: string | null;
  avatarUrl: string;
  bannerUrl: string;
  /** Skill names — upserted into the Skill table by the seeder. */
  skills: string[];
  /** Interest slugs. Must exist in the reference data seeded by prisma/seed.ts. */
  interests: string[];
  /** ISO date. Spread across the last twelve months. */
  joinedAt: string;
  /**
   * Reach, 0..1. Drives follower count and how much engagement this person's
   * posts attract. Deliberately uneven — a community where everyone has the same
   * reach is the clearest tell that the numbers were made up.
   */
  influence: number;
}

